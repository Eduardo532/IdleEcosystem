    /** Escalera del Grimorio: "<Edificio>: <Escalón>" se arma con las dos partes. */
    private fun ladderName(text: String): String? {
        val building = text.substringBeforeLast(": ", missingDelimiterValue = "")
        val rung = text.substringAfterLast(": ")
        if (building.isEmpty()) return null
        val buildingEn = BUILDINGS[building] ?: return null
        val rungEn = LADDER[rung] ?: return null
        return "$buildingEn: $rungEn"
    }

