 * Los catálogos siguen escritos en español dentro del código (es el idioma original y
 * el que usan los guardados y los tests), y esta tabla se aplica solo al mostrarlos.
 * La clave es el texto original en español: así el texto que llega a la pantalla, sea
 * del catálogo o de un evento ya resuelto (el resultado de una opción), se traduce igual.
 *
 * ContentTranslationsTest recorre todos los catálogos y falla si algún texto visible
